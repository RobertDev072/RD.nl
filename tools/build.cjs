// Builds the static site (index.html, assets/js/*, sitemap.xml, robots.txt)
// from the Claude Design sources in /design.
// Usage: DOMAIN=https://www.jouwdomein.nl node tools/build.cjs
const fs = require('fs');
const path = require('path');
const { render, parse } = require('./dc-render.js');

const ROOT = path.join(__dirname, '..');
const DOMAIN = (process.env.DOMAIN || 'https://www.JOUWDOMEIN.nl').replace(/\/$/, '');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const write = (p, s) => { fs.mkdirSync(path.dirname(path.join(ROOT, p)), { recursive: true }); fs.writeFileSync(path.join(ROOT, p), s); };

// Uploaded canvas images -> files in assets/img
const BLOBS = {
  '510226f31c6efd31f8741662d4a071e4': 'assets/img/sg-desktop.webp',
  'c47f304cea5d5b27e3ee34111238247c': 'assets/img/sg-mobile.webp',
  'ab8d42dcb29b05d3a3052cd4bc71d063': 'assets/img/bn-desktop.webp',
  '3ee9f70ea453705c02be135dd0241ff0': 'assets/img/bn-mobile.webp',
  '4b73d610c1e7a090e9c8cc971086cfd7': 'assets/img/vp-desktop.webp',
  '5968cc0312d3fdb370ba16570e2f7531': 'assets/img/vp-mobile.webp',
  'ee115767728c35a4c7647ed01262d576': 'assets/img/gt-desktop.webp',
  'df1730b3d2100c794a6844a2e2da64bc': 'assets/img/gt-mobile.webp',
  'cf5c94529c5aad6fc237eca8a5491dbc': 'assets/img/logo-white.png'
};
const blobs = (s) => s.replace(/\/_blob\/([0-9a-f]{32})/g, (m, id) => BLOBS[id] || m);

class DCLogic { constructor(props) { this.props = props || {}; this.state = {}; } setState(s) { Object.assign(this.state, s); } forceUpdate() {} }
function component(script, state) {
  const C = new Function('DCLogic', script + '\nreturn Component;')(DCLogic);
  const c = new C({});
  Object.assign(c.state, state);
  return c.renderVals();
}

const main = parse(read('design/Main.dc.html'));
const flow = parse(read('design/Flow.dc.html'));

// Static render of the animation's end state (shown without JS / with reduced motion)
const flowHtml = render(flow.body, component(flow.script, { t: 14.5 }));

let body = render(main.body, component(main.script, { step: 3 }));
body = body.replace(/<dc-import name="Flow"[^>]*><\/dc-import>/, '<div id="flow">' + flowHtml + '</div>');
// lazy-load everything below the hero
const cut = body.indexOf('<!-- MARQUEE -->');
body = body.slice(0, cut) + body.slice(cut).replace(/<img /g, '<img loading="lazy" decoding="async" ');
body = blobs(body);

const links = new Set();
[main.helmet, flow.helmet].forEach((h) => (h.match(/<link[^>]+>/g) || []).forEach((l) => links.add(l)));
const styles = [main.helmet, flow.helmet].map((h) => (h.match(/<style>([\s\S]*?)<\/style>/) || [])[1] || '').join('\n');

const seo = read('design/seo-head.html')
  .replace(/<!--[\s\S]*?-->\s*/, '').replace(/<html[^>]*>\s*/, '').replace(/<title>[\s\S]*?<\/title>\s*/, '')
  .replace(/https:\/\/www\.JOUWDOMEIN\.nl/g, DOMAIN);

const html = `<!doctype html>
<html lang="nl">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${main.title}</title>
${seo.trim()}
<link rel="icon" href="assets/img/logo.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
${[...links].join('\n')}
<style>
${styles}
.rd .reveal{animation:rv .9s cubic-bezier(.2,.7,.2,1) both}
.rd h1 .reveal:nth-child(2){animation-delay:.2s}
.rd p.reveal{animation-delay:.4s}
@keyframes rv{from{opacity:0;filter:blur(10px);transform:translateY(14px)}}
@media (prefers-reduced-motion:reduce){.rd .reveal{animation:none}}
</style>
</head>
<body>
${body}
<script src="assets/js/dc-render.js" defer></script>
<script src="assets/js/flow.js" defer></script>
</body>
</html>
`;
write('index.html', html);

// Client runtime for the animation: same template + logic as the design file
write('assets/js/dc-render.js', read('tools/dc-render.js'));
write('assets/js/flow.js', `// Generated by tools/build.cjs from design/Flow.dc.html
(function () {
  var host = document.getElementById('flow');
  if (!host || !window.DCRender) return;
  var TPL = ${JSON.stringify(flow.body)};
  var pending = false, comp;
  function paint() {
    pending = false;
    var t = document.createElement('template');
    t.innerHTML = DCRender.render(TPL, comp.renderVals());
    var next = t.content.firstElementChild;
    if (host.firstElementChild && next) DCRender.morph(host.firstElementChild, next);
    else host.innerHTML = t.innerHTML;
  }
  class DCLogic {
    constructor(props) { this.props = props || {}; this.state = {}; }
    setState(s) { Object.assign(this.state, s); if (!pending) { pending = true; requestAnimationFrame(paint); } }
    forceUpdate() { this.setState({}); }
  }
${flow.script.replace(/^/gm, '  ')}
  comp = new Component({});
  paint();
  var started = false;
  new IntersectionObserver(function (es) {
    if (es[0].isIntersecting && !started) { started = true; comp.componentDidMount && comp.componentDidMount(); }
  }).observe(host);
})();
`);

write('sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url><loc>${DOMAIN}/</loc><lastmod>${new Date().toISOString().slice(0, 10)}</lastmod><priority>1.0</priority></url>
</urlset>
`);
write('robots.txt', `User-agent: *\nAllow: /\n\nSitemap: ${DOMAIN}/sitemap.xml\n`);
console.log('Built index.html (' + html.length + ' bytes) for ' + DOMAIN);
